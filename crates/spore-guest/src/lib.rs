//! The guest half of a Spore.
//!
//! A Spore is a module (wasm) plus a UI (Lua) plus a manifest. This crate is
//! the boundary in the middle: it owns a PUC Lua 5.4 state, loads the view the
//! package carries, and exposes the surface contract -- `observe`, `present`,
//! `input`, `close` -- with no knowledge of pixels, windows or GPUs.
//!
//! Everything above it (winit, a browser page, a bridge over HTTP/SSE) is a
//! host adapter for `soil:surface`. Everything below it is the view's own data.

use std::sync::{Arc, Mutex};

pub mod scene;

pub use scene::Command;

/// What the host tells the view for one invocation.
#[derive(Clone, Debug, Default)]
pub struct Frame {
    pub width: u32,
    pub height: u32,
    pub hover: String,
    pub pressed: String,
    pub focus: String,
    pub selected: String,
    pub scroll: f32,
    pub pointer: (f32, f32),
}

/// The surface state a host observes and hands back. Mirrors `soil:surface.state`.
#[derive(Clone, Debug, PartialEq)]
pub struct State {
    pub generation: u64,
    pub theme_generation: u64,
    pub width: u32,
    pub height: u32,
    pub scale: f32,
    pub focused: bool,
    pub visible: bool,
}

impl State {
    fn new(generation: u64, width: u32, height: u32) -> Self {
        Self { generation, theme_generation: 0, width, height, scale: 1.0, focused: true, visible: true }
    }
}

pub struct Guest {
    lua: mlua::Lua,
    render: mlua::Function,
    commands: Arc<Mutex<Vec<serde_json::Value>>>,
    state: State,
}

/// The view and the loader, exactly as the browser bundle has them.
fn bundle() -> String {
    let mut out = String::from("-- generated by spore-guest\n");
    out += include_str!("../../soil-ui-spike/browser/prelude.lua");
    for (name, source) in [
        ("theme.lua", include_str!("../../soil-ui-spike/theme.lua")),
        ("ui.lua", include_str!("../../soil-ui-spike/ui.lua")),
        ("components/button.lua", include_str!("../../soil-ui-spike/components/button.lua")),
        ("components/nav_row.lua", include_str!("../../soil-ui-spike/components/nav_row.lua")),
        ("components/paragraph.lua", include_str!("../../soil-ui-spike/components/paragraph.lua")),
        ("view.lua", include_str!("../../soil-ui-spike/view.lua")),
    ] {
        out += &format!("SOIL.modules[{name:?}] = function()\n{source}\nend\n");
    }
    out += include_str!("../../soil-ui-spike/browser/driver.lua");
    out
}

impl Guest {
    pub fn new(width: u32, height: u32) -> anyhow::Result<Self> {
        // mlua's error is not Send/Sync, so it is converted once, here, rather
        // than at every call inside the builder.
        Self::build(width, height).map_err(|error| anyhow::anyhow!("lua: {error}"))
    }

    fn build(width: u32, height: u32) -> mlua::Result<Self> {
        let lua = mlua::Lua::new();
        let commands = Arc::new(Mutex::new(Vec::new()));

        {
            let sink = commands.clone();
            lua.globals().set(
                "rect",
                lua.create_function(move |_, (x, y, w, h, r, c): (f32, f32, f32, f32, f32, String)| {
                    sink.lock().unwrap().push(serde_json::json!(["rect", x, y, w, h, r, c]));
                    Ok(())
                })?,
            )?;
            let sink = commands.clone();
            lua.globals().set(
                "text",
                lua.create_function(move |_, (v, x, y, size, c, a, al, f, wrap): (String, f32, f32, f32, String, String, String, String, Option<f32>)| {
                    sink.lock().unwrap().push(serde_json::json!(["text", v, x, y, size, c, a, al, f, wrap]));
                    Ok(())
                })?,
            )?;
            let sink = commands.clone();
            lua.globals().set(
                "hit",
                lua.create_function(move |_, (id, x, y, w, h, a): (String, f32, f32, f32, f32, String)| {
                    sink.lock().unwrap().push(serde_json::json!(["hit", id, x, y, w, h, a]));
                    Ok(())
                })?,
            )?;
            let sink = commands.clone();
            lua.globals().set(
                "group",
                lua.create_function(move |_, key: String| {
                    sink.lock().unwrap().push(serde_json::json!(["group", key]));
                    Ok(())
                })?,
            )?;
            let sink = commands.clone();
            lua.globals().set(
                "clip",
                lua.create_function(move |_, args: mlua::Variadic<f32>| {
                    let mut sink = sink.lock().unwrap();
                    if args.len() == 4 {
                        sink.push(serde_json::json!(["clip", args[0], args[1], args[2], args[3]]));
                    } else {
                        sink.push(serde_json::json!(["clip-end"]));
                    }
                    Ok(())
                })?,
            )?;
            lua.globals().set(
                "measure",
                lua.create_function(move |_, (value, size, _font, _wrap): (String, f32, Option<String>, Option<f32>)| {
                    // The host measures with a shaper; a guest without one
                    // estimates, exactly as the page does.
                    Ok((value.chars().count() as f32 * size * 0.52, size * 1.25))
                })?,
            )?;
        }

        lua.load(bundle()).set_name("spore").exec()?;
        let soil: mlua::Table = lua.globals().get("SOIL")?;
        let render: mlua::Function = soil.get("render")?;

        Ok(Self { lua, render, commands, state: State::new(1, width, height) })
    }

    /// The surface state, without presenting.
    pub fn observe(&self) -> State {
        self.state.clone()
    }

    /// Render one frame. Returns the scene document and the new state.
    pub fn present(&mut self, frame: &Frame) -> anyhow::Result<(State, Vec<Command>)> {
        let document = self.render_document(frame).map_err(|error| anyhow::anyhow!("lua: {error}"))?;
        let raw: Vec<serde_json::Value> = serde_json::from_str(&document)?;
        self.commands.lock().unwrap().clear();

        self.state.generation += 1;
        self.state.width = frame.width.max(1);
        self.state.height = frame.height.max(1);
        Ok((self.state.clone(), raw.iter().filter_map(Command::from_json).collect()))
    }

    fn render_document(&self, frame: &Frame) -> mlua::Result<String> {
        let table = self.lua.create_table()?;
        table.set("width", frame.width.max(1))?;
        table.set("height", frame.height.max(1))?;
        table.set("hover", frame.hover.clone())?;
        table.set("pressed", frame.pressed.clone())?;
        table.set("focus", frame.focus.clone())?;
        table.set("selected", frame.selected.clone())?;
        table.set("scroll", frame.scroll)?;
        let pointer = self.lua.create_table()?;
        pointer.set("x", frame.pointer.0)?;
        pointer.set("y", frame.pointer.1)?;
        table.set("pointer", pointer)?;

        self.render.call(table)
    }

    /// One normalized event. The view is stateless today, so this only moves
    /// the generation; hit-testing still happens in the host and moves here as
    /// the surface migration lands.
    pub fn input(&mut self, _event: scene::Input) -> State {
        self.state.generation += 1;
        self.state.clone()
    }
}

//! Generate a Lua SDK from the canonical Soil WIT contracts.
//!
//! The generated module is deliberately a thin binding, not a second host. It
//! turns every WIT free function into a Lua function that calls one host
//! dispatcher with named arguments. Resources stay opaque host values; methods
//! receive them as `self`. The canonical WIT remains the contract, and the host
//! implementation remains the only authority.

use std::collections::BTreeSet;
use std::path::Path;

use anyhow::{Context, Result, bail};
use serde_json::{Value, json};
use wit_parser::{
    Docs, Enum, Flags, Function, FunctionKind, Record, Resolve, SourceMap, Type, TypeDef,
    TypeDefKind, TypeId, UnresolvedPackage, UnresolvedPackageGroup, Variant,
};

/// Generated Lua source and the machine-readable signature manifest.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Generated {
    pub lua: String,
    pub manifest: String,
}

/// Loads every `.wit` package in `wit_dir` into one resolve.
///
/// The canonical `wit/` directory stores one package per file. `wit-parser`
/// resolves a directory as one package, so this loads files individually and
/// topologically orders them by their declared foreign dependencies.
pub fn load(wit_dir: &Path) -> Result<Resolve> {
    let mut files = Vec::new();
    for entry in std::fs::read_dir(wit_dir)
        .with_context(|| format!("read WIT directory {}", wit_dir.display()))?
    {
        let path = entry?.path();
        if path.extension().and_then(|value| value.to_str()) == Some("wit") {
            files.push(path);
        }
    }
    files.sort();
    if files.is_empty() {
        bail!("no .wit files in {}", wit_dir.display());
    }

    let mut units = Vec::new();
    for file in files {
        let group = UnresolvedPackageGroup::parse_file(&file)
            .with_context(|| format!("parse WIT {}", file.display()))?;
        let source_map = group.source_map.clone();
        for nested in group.nested {
            units.push(Unit {
                name: nested.name.to_string(),
                package: nested,
                source_map: source_map.clone(),
            });
        }
        units.push(Unit {
            name: group.main.name.to_string(),
            package: group.main,
            source_map: group.source_map,
        });
    }

    let mut resolve = Resolve::default();
    let mut pushed = BTreeSet::new();
    while !units.is_empty() {
        let mut pending = Vec::new();
        let mut progressed = false;
        for unit in units {
            let ready = unit
                .package
                .foreign_deps
                .keys()
                .all(|dependency| pushed.contains(&dependency.to_string()));
            if ready {
                resolve
                    .push(unit.package, &unit.source_map)
                    .with_context(|| format!("resolve WIT package {}", unit.name))?;
                pushed.insert(unit.name);
                progressed = true;
            } else {
                pending.push(unit);
            }
        }
        if !progressed {
            let waiting = pending
                .iter()
                .map(|unit| unit.name.clone())
                .collect::<Vec<_>>()
                .join(", ");
            bail!("unresolved WIT packages (missing dependency or cycle): {waiting}");
        }
        units = pending;
    }
    Ok(resolve)
}

/// Generates the Lua module and manifest for all packages, or one package when
/// `package` is set.
pub fn generate(wit_dir: &Path, package: Option<&str>) -> Result<Generated> {
    let resolve = load(wit_dir)?;
    generate_from_resolve(&resolve, package)
}

/// Generates from an already-loaded [`Resolve`]. Useful for tests and build
/// scripts that already parsed a WIT graph.
pub fn generate_from_resolve(resolve: &Resolve, package: Option<&str>) -> Result<Generated> {
    let mut packages = resolve
        .packages
        .iter()
        .map(|(_, package)| package)
        .collect::<Vec<_>>();
    if let Some(package) = package {
        packages.retain(|candidate| candidate.name.to_string() == package);
        if packages.is_empty() {
            bail!("unknown WIT package '{package}'");
        }
    }
    packages.sort_by_key(|package| package.name.to_string());

    let mut lua = String::from(
        r#"-- Generated by soil-sdk-lua from the canonical WIT contracts.
-- Do not edit by hand.

local M = {}

local function dispatch(interface_id, function_name, args, self)
  if type(__soil_call) ~= "function" then
    error("soil: host does not provide __soil_call", 3)
  end
  return __soil_call(interface_id, function_name, args or {}, self)
end
"#,
    );
    let mut declared = BTreeSet::new();
    let mut package_json = Vec::new();

    for package in &packages {
        let package_name = package.name.to_string();
        let namespace_path = format!("M.{}", lua_ident(&package.name.namespace));
        let package_path = format!("{namespace_path}.{}", lua_ident(&package.name.name));
        ensure_table(&mut lua, &mut declared, &namespace_path);
        ensure_table(&mut lua, &mut declared, &package_path);

        let mut interfaces = package.interfaces.iter().collect::<Vec<_>>();
        interfaces.sort_by_key(|(name, _)| *name);
        let mut interface_json = Vec::new();

        for (interface_name, interface_id) in &interfaces {
            let interface = &resolve.interfaces[**interface_id];
            let Some(name) = interface.name.as_deref() else {
                continue;
            };
            let interface_path = format!("{package_path}.{}", lua_ident(name));
            ensure_table(&mut lua, &mut declared, &interface_path);
            let interface_id = format!("{package_name}/{name}");

            let _ = interface_name;
            if let Some(docs) = docs(&interface.docs) {
                lua.push_str(&docs);
            }

            let mut types = interface.types.iter().collect::<Vec<_>>();
            types.sort_by_key(|(name, _)| *name);
            let types_path = format!("{interface_path}.types");
            let mut type_json = Vec::new();
            if !types.is_empty() {
                ensure_table(&mut lua, &mut declared, &types_path);
                for (type_name, type_id) in types {
                    let type_def = &resolve.types[*type_id];
                    lua_type(&mut lua, &types_path, type_name, type_def, resolve);
                    type_json.push(type_json_value(resolve, type_name, type_def));
                }
            }

            let mut functions = interface.functions.iter().collect::<Vec<_>>();
            functions.sort_by_key(|(name, _)| *name);
            let mut function_json = Vec::new();
            for (function_name, function) in functions {
                let resource = function.kind.resource().map(|id| {
                    resolve.types[id]
                        .name
                        .clone()
                        .unwrap_or_else(|| "resource".to_owned())
                });
                if let Some(resource) = &resource {
                    let resource_path = format!("{interface_path}.{}", lua_type_ident(resource));
                    ensure_table(&mut lua, &mut declared, &resource_path);
                }

                lua_function(
                    &mut lua,
                    resolve,
                    &interface_path,
                    &interface_id,
                    function_name,
                    function,
                    resource.as_deref(),
                );
                function_json.push(function_json_value(
                    resolve,
                    function_name,
                    function,
                    resource.as_deref(),
                ));
            }

            interface_json.push(json!({
                "name": name,
                "id": interface_id,
                "docs": docs_text(&interface.docs),
                "types": type_json,
                "functions": function_json,
            }));
        }

        if let Some((name, _)) = interfaces
            .iter()
            .find(|(_, id)| resolve.interfaces[**id].name.is_some())
            && interfaces
                .iter()
                .filter(|(_, id)| resolve.interfaces[**id].name.is_some())
                .count()
                == 1
        {
            lua.push_str(&format!(
                "{package_path} = {package_path}.{}\n",
                lua_ident(name)
            ));
        }

        package_json.push(json!({
            "id": package_name,
            "namespace": package.name.namespace,
            "name": package.name.name,
            "version": package.name.version.as_ref().map(ToString::to_string),
            "docs": docs_text(&package.docs),
            "interfaces": interface_json,
        }));
    }

    lua.push_str("\nreturn M\n");
    let manifest = serde_json::to_string_pretty(&json!({
        "schema": 1,
        "generator": "soil-sdk-lua",
        "dispatcher": "__soil_call(interface_id, function_name, args, self)",
        "packages": package_json,
    }))?;

    Ok(Generated { lua, manifest })
}

struct Unit {
    name: String,
    package: UnresolvedPackage,
    source_map: SourceMap,
}

fn ensure_table(lua: &mut String, declared: &mut BTreeSet<String>, path: &str) {
    let parts = path.split('.').collect::<Vec<_>>();
    for end in 1..=parts.len() {
        let prefix = parts[..end].join(".");
        if prefix != "M" && declared.insert(prefix.clone()) {
            lua.push_str(&format!("{prefix} = {prefix} or {{}}\n"));
        }
    }
}

fn lua_function(
    lua: &mut String,
    resolve: &Resolve,
    interface_path: &str,
    interface_id: &str,
    function_name: &str,
    function: &Function,
    resource: Option<&str>,
) {
    if let Some(docs) = docs(&function.docs) {
        lua.push_str(&docs);
    }
    let member = function_member(function_name, &function.kind);
    let lua_name = lua_ident(&member);
    let result = function
        .result
        .as_ref()
        .map(|ty| format!(" -> {}", field_type_label(resolve, ty)))
        .unwrap_or_default();
    lua.push_str(&format!("-- WIT: {function_name}{result}\n"));
    if matches!(
        &function.kind,
        FunctionKind::AsyncFreestanding
            | FunctionKind::AsyncMethod(_)
            | FunctionKind::AsyncStatic(_)
    ) {
        lua.push_str("-- async: the host returns a future handle\n");
    }

    match resource {
        Some(resource) => {
            let resource_path = format!("{interface_path}.{}", lua_type_ident(resource));
            let dispatch_name = format!("{resource}.{member}");
            match &function.kind {
                FunctionKind::Method(_) | FunctionKind::AsyncMethod(_) => {
                    lua.push_str(&format!(
                        "function {resource_path}:{lua_name}(args)\n  return dispatch({interface_id:?}, {dispatch_name:?}, args, self)\nend\n"
                    ));
                }
                _ => {
                    lua.push_str(&format!(
                        "function {resource_path}.{lua_name}(args)\n  return dispatch({interface_id:?}, {dispatch_name:?}, args)\nend\n"
                    ));
                }
            }
        }
        None => {
            lua.push_str(&format!(
                "function {interface_path}.{lua_name}(args)\n  return dispatch({interface_id:?}, {function_name:?}, args)\nend\n"
            ));
        }
    }
}

fn lua_type(lua: &mut String, path: &str, name: &str, type_def: &TypeDef, resolve: &Resolve) {
    let lua_name = lua_type_ident(name);
    match &type_def.kind {
        TypeDefKind::Enum(Enum { cases }) => {
            let fields = cases
                .iter()
                .map(|case| format!("{} = {:?}", lua_const(&case.name), case.name))
                .collect::<Vec<_>>()
                .join(", ");
            lua.push_str(&format!("{path}.{lua_name} = {{ {fields} }}\n"));
        }
        TypeDefKind::Flags(Flags { flags }) => {
            let fields = flags
                .iter()
                .map(|flag| format!("{} = {:?}", lua_const(&flag.name), flag.name))
                .collect::<Vec<_>>()
                .join(", ");
            lua.push_str(&format!("{path}.{lua_name} = {{ {fields} }}\n"));
        }
        TypeDefKind::Record(Record { fields }) => {
            let fields = fields
                .iter()
                .map(|field| {
                    format!(
                        "{{ name = {:?}, type = {:?} }}",
                        field.name,
                        field_type_label(resolve, &field.ty)
                    )
                })
                .collect::<Vec<_>>()
                .join(", ");
            lua.push_str(&format!(
                "{path}.{lua_name} = {{ fields = {{ {fields} }} }}\n"
            ));
        }
        TypeDefKind::Variant(Variant { cases }) => {
            let tags = cases
                .iter()
                .map(|case| format!("{} = {:?}", lua_const(&case.name), case.name))
                .collect::<Vec<_>>()
                .join(", ");
            lua.push_str(&format!("{path}.{lua_name} = {{ {tags} }}\n"));
        }
        TypeDefKind::Type(ty) => {
            lua.push_str(&format!(
                "{path}.{lua_name} = {{ type = {:?} }}\n",
                field_type_label(resolve, ty)
            ));
        }
        TypeDefKind::Resource => {
            lua.push_str(&format!("{path}.{lua_name} = {{ resource = true }}\n"));
        }
        _ => {}
    }
}

fn type_json_value(resolve: &Resolve, name: &str, type_def: &TypeDef) -> Value {
    let mut value = json!({
        "name": name,
        "lua": lua_type_ident(name),
        "kind": type_def.kind.as_str(),
        "docs": docs_text(&type_def.docs),
    });
    match &type_def.kind {
        TypeDefKind::Record(Record { fields }) => {
            value["fields"] = fields
                .iter()
                .map(|field| json!({"name": field.name, "type": field_type_label(resolve, &field.ty)}))
                .collect();
        }
        TypeDefKind::Enum(Enum { cases }) => {
            value["cases"] = cases.iter().map(|case| json!(case.name)).collect();
        }
        TypeDefKind::Flags(Flags { flags }) => {
            value["flags"] = flags.iter().map(|flag| json!(flag.name)).collect();
        }
        TypeDefKind::Variant(Variant { cases }) => {
            value["cases"] = cases
                .iter()
                .map(|case| json!({"name": case.name, "type": case.ty.as_ref().map(|ty| field_type_label(resolve, ty))}))
                .collect();
        }
        TypeDefKind::Type(ty) => {
            value["type"] = json!(field_type_label(resolve, ty));
        }
        _ => {}
    }
    value
}

fn function_json_value(
    resolve: &Resolve,
    name: &str,
    function: &Function,
    resource: Option<&str>,
) -> Value {
    let member = function_member(name, &function.kind);
    json!({
        "name": name,
        "member": member,
        "lua": lua_ident(&member),
        "kind": kind_label(&function.kind),
        "resource": resource,
        "params": function
            .params
            .iter()
            .map(|(name, ty)| json!({"name": name, "type": field_type_label(resolve, ty)}))
            .collect::<Vec<_>>(),
        "result": function.result.as_ref().map(|ty| field_type_label(resolve, ty)),
        "docs": docs_text(&function.docs),
    })
}

fn function_member(name: &str, kind: &FunctionKind) -> String {
    let rest = name.rsplit_once(']').map_or(name, |(_, rest)| rest);
    match kind {
        FunctionKind::Constructor(_) => "new".to_owned(),
        FunctionKind::Method(_)
        | FunctionKind::AsyncMethod(_)
        | FunctionKind::Static(_)
        | FunctionKind::AsyncStatic(_) => rest
            .split_once('.')
            .map_or(rest, |(_, member)| member)
            .to_owned(),
        FunctionKind::Freestanding | FunctionKind::AsyncFreestanding => name.to_owned(),
    }
}

fn kind_label(kind: &FunctionKind) -> &'static str {
    match kind {
        FunctionKind::Freestanding => "freestanding",
        FunctionKind::AsyncFreestanding => "async-freestanding",
        FunctionKind::Method(_) => "method",
        FunctionKind::AsyncMethod(_) => "async-method",
        FunctionKind::Static(_) => "static",
        FunctionKind::AsyncStatic(_) => "async-static",
        FunctionKind::Constructor(_) => "constructor",
    }
}

fn field_type_label(resolve: &Resolve, ty: &Type) -> String {
    match ty {
        Type::Bool => "bool".into(),
        Type::U8 => "u8".into(),
        Type::U16 => "u16".into(),
        Type::U32 => "u32".into(),
        Type::U64 => "u64".into(),
        Type::S8 => "s8".into(),
        Type::S16 => "s16".into(),
        Type::S32 => "s32".into(),
        Type::S64 => "s64".into(),
        Type::F32 => "f32".into(),
        Type::F64 => "f64".into(),
        Type::Char => "char".into(),
        Type::String => "string".into(),
        Type::ErrorContext => "error-context".into(),
        Type::Id(id) => type_id_label(resolve, *id),
    }
}

fn type_id_label(resolve: &Resolve, id: TypeId) -> String {
    let definition = &resolve.types[id];
    if let Some(name) = &definition.name {
        return name.clone();
    }
    type_def_label(resolve, &definition.kind)
}

fn type_def_label(resolve: &Resolve, kind: &TypeDefKind) -> String {
    match kind {
        TypeDefKind::Record(_) => "record".into(),
        TypeDefKind::Resource => "resource".into(),
        TypeDefKind::Handle(handle) => match handle {
            wit_parser::Handle::Own(id) => format!("own<{}>", type_id_label(resolve, *id)),
            wit_parser::Handle::Borrow(id) => {
                format!("borrow<{}>", type_id_label(resolve, *id))
            }
        },
        TypeDefKind::Flags(_) => "flags".into(),
        TypeDefKind::Tuple(tuple) => {
            let types = tuple
                .types
                .iter()
                .map(|ty| field_type_label(resolve, ty))
                .collect::<Vec<_>>()
                .join(", ");
            format!("tuple<{types}>")
        }
        TypeDefKind::Variant(_) => "variant".into(),
        TypeDefKind::Enum(_) => "enum".into(),
        TypeDefKind::Option(ty) => format!("option<{}>", field_type_label(resolve, ty)),
        TypeDefKind::Result(result) => format!(
            "result<{}, {}>",
            result
                .ok
                .as_ref()
                .map(|ty| field_type_label(resolve, ty))
                .unwrap_or_else(|| "_".into()),
            result
                .err
                .as_ref()
                .map(|ty| field_type_label(resolve, ty))
                .unwrap_or_else(|| "_".into())
        ),
        TypeDefKind::List(ty) => format!("list<{}>", field_type_label(resolve, ty)),
        TypeDefKind::FixedSizeList(ty, size) => {
            format!("list<{}, {}>", field_type_label(resolve, ty), size)
        }
        TypeDefKind::Future(ty) => format!(
            "future<{}>",
            ty.as_ref()
                .map(|ty| field_type_label(resolve, ty))
                .unwrap_or_else(|| "_".into())
        ),
        TypeDefKind::Stream(ty) => format!(
            "stream<{}>",
            ty.as_ref()
                .map(|ty| field_type_label(resolve, ty))
                .unwrap_or_else(|| "_".into())
        ),
        TypeDefKind::Type(ty) => field_type_label(resolve, ty),
        TypeDefKind::Unknown => "unknown".into(),
    }
}

fn docs(docs: &Docs) -> Option<String> {
    let contents = docs.contents.as_deref()?;
    if contents.trim().is_empty() {
        return None;
    }
    let mut out = String::new();
    for line in contents.lines() {
        out.push_str("--- ");
        out.push_str(line.trim_end());
        out.push('\n');
    }
    Some(out)
}

fn docs_text(docs: &Docs) -> Option<String> {
    docs.contents
        .as_deref()
        .filter(|contents| !contents.trim().is_empty())
        .map(ToOwned::to_owned)
}

fn lua_ident(name: &str) -> String {
    let mut out = name.replace('-', "_");
    if out.is_empty() {
        out.push('_');
    }
    if out.as_bytes()[0].is_ascii_digit() {
        out.insert(0, '_');
    }
    if LUA_KEYWORDS.contains(&out.as_str()) {
        out.insert(0, '_');
    }
    out
}

fn lua_type_ident(name: &str) -> String {
    let mut out = String::new();
    for part in name.split('-') {
        let mut chars = part.chars();
        if let Some(first) = chars.next() {
            out.extend(first.to_uppercase());
            out.push_str(chars.as_str());
        }
    }
    if out.is_empty() {
        out.push('_');
    }
    if out.as_bytes()[0].is_ascii_digit() {
        out.insert(0, '_');
    }
    out
}

fn lua_const(name: &str) -> String {
    let mut out = name.replace('-', "_").to_ascii_uppercase();
    if out.is_empty() {
        out.push('_');
    }
    if out.as_bytes()[0].is_ascii_digit() {
        out.insert(0, '_');
    }
    out
}

const LUA_KEYWORDS: &[&str] = &[
    "and", "break", "do", "else", "elseif", "end", "false", "for", "function", "goto", "if", "in",
    "local", "nil", "not", "or", "repeat", "return", "then", "true", "until", "while",
];

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn checked_in_sdk_matches_the_canonical_wit() {
        let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
        let generated = generate(&root.join("wit"), None).unwrap();
        assert_eq!(generated.lua, include_str!("../generated/soil.lua"));
        assert_eq!(
            generated.manifest,
            include_str!("../generated/soil-sdk.json")
        );

        let mut vm = luna_core::vm::Vm::new_minimal(luna_core::version::LuaVersion::Lua54);
        vm.open_base();
        let native = vm.native(dispatch_probe);
        vm.set_global("__soil_call", native).unwrap();
        let module = match vm.eval(&generated.lua) {
            Ok(module) => module,
            Err(error) => panic!("generated Lua failed: {}", vm.error_text(&error)),
        };
        vm.set_global("sdk", module[0]).unwrap();
        let result = vm
            .eval("return sdk.soil.http.fetch({ url = 'https://example.com' })")
            .unwrap();
        assert_eq!(
            String::from_utf8_lossy(as_str(&result[0])),
            "soil:http@0.1.0/http|fetch"
        );
    }

    #[test]
    fn generates_a_callable_lua_module() {
        let directory = tempfile::tempdir().unwrap();
        std::fs::write(
            directory.path().join("demo.wit"),
            r#"
                package test:demo@0.1.0;

                interface demo {
                    enum mode { fast, slow }
                    record request { url: string }
                    fetch: func(request: request) -> string;
                }

                world guest { import demo; }
            "#,
        )
        .unwrap();

        let generated = generate(directory.path(), None).unwrap();
        assert!(
            generated
                .lua
                .contains("function M.test.demo.demo.fetch(args)")
        );
        assert!(generated.lua.contains("FAST = \"fast\""));
        assert!(generated.manifest.contains("test:demo@0.1.0/demo"));

        let mut vm = luna_core::vm::Vm::new_minimal(luna_core::version::LuaVersion::Lua54);
        vm.open_base();
        let native = vm.native(dispatch_probe);
        vm.set_global("__soil_call", native).unwrap();
        let module = vm.eval(&generated.lua).unwrap();
        vm.set_global("sdk", module[0]).unwrap();
        let result = vm
            .eval("return sdk.test.demo.fetch({ url = 'https://example.com' })")
            .unwrap();
        assert_eq!(
            String::from_utf8_lossy(as_str(&result[0])),
            "test:demo@0.1.0/demo|fetch"
        );
        let enum_value = vm.eval("return sdk.test.demo.types.Mode.FAST").unwrap();
        assert_eq!(String::from_utf8_lossy(as_str(&enum_value[0])), "fast");
    }

    fn dispatch_probe(
        vm: &mut luna_core::vm::Vm,
        func_slot: u32,
        nargs: u32,
    ) -> Result<u32, luna_core::vm::LuaError> {
        let interface_value = vm.nat_arg(func_slot, nargs, 0);
        let function_value = vm.nat_arg(func_slot, nargs, 1);
        let interface = as_str(&interface_value);
        let function = as_str(&function_value);
        let value = format!(
            "{}|{}",
            String::from_utf8_lossy(interface),
            String::from_utf8_lossy(function)
        );
        let value = vm.heap.intern(value.as_bytes());
        Ok(vm.nat_return(func_slot, &[luna_core::runtime::Value::Str(value)]))
    }

    fn as_str(value: &luna_core::runtime::Value) -> &[u8] {
        match value {
            luna_core::runtime::Value::Str(value) => value.as_bytes(),
            _ => panic!("expected a Lua string, got {value:?}"),
        }
    }
}

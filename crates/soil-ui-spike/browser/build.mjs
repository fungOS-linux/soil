// Bundle the Lua view into one chunk for the browser: no filesystem, no
// package path, just the sources the spore ships. These are the same files the
// native host loads with dofile/require.
import fs from "node:fs";
import path from "node:path";
import url from "node:url";

const here = path.dirname(url.fileURLToPath(import.meta.url));
const crate = path.resolve(here, "..");

const files = [
  "theme.lua",
  "ui.lua",
  "components/button.lua",
  "components/nav_row.lua",
  "components/paragraph.lua",
  "view.lua",
];

const prelude = fs.readFileSync(path.join(here, "prelude.lua"), "utf8");
const driver = fs.readFileSync(path.join(here, "driver.lua"), "utf8");

let bundle = "-- generated by browser/build.mjs; do not edit\n";
bundle += prelude + "\n";
for (const file of files) {
  const source = fs.readFileSync(path.join(crate, file), "utf8");
  bundle += `SOIL.modules[${JSON.stringify(file)}] = function()\n${source}\nend\n`;
}
bundle += driver;

fs.writeFileSync(path.join(here, "bundle.lua"), bundle);
console.log(`bundle.lua: ${bundle.length} bytes from ${files.length} files`);

// The page fetches next to itself, so the engine lands beside the sources.
for (const name of ["spore.wasm", "lua.wasm"]) {
  const source = path.resolve(crate, name);
  if (fs.existsSync(source)) {
    fs.copyFileSync(source, path.join(here, name));
    console.log(`${name}: copied ${fs.statSync(source).size} bytes`);
  } else {
    console.warn(`no ${source} — build it in lua-wasi and copy it here`);
  }
}
